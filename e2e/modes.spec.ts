import { expect, test, type Locator, type Page } from '@playwright/test'

async function mode(page: Page, name: string) {
  await page.getByRole('navigation', { name: 'Calculator modes' }).getByRole('button', { name, exact: true }).click()
}
async function tableValues(table: Locator) {
  return table.getByRole('cell').allTextContents()
}
const numericOutput = async (page: Page) => Number(await page.getByLabel('Converted value').textContent())
const savedView = async (page: Page) => page.evaluate(() => JSON.parse(localStorage.getItem('cp.graph.view') || '{}') as { cx: number; cy: number; s: number })

const browserErrors = new WeakMap<Page, string[]>()
test.beforeEach(async ({ page }) => {
  const errors: string[] = []
  browserErrors.set(page, errors)
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.goto('/')
})
test.afterEach(async ({ page }) => { expect(browserErrors.get(page), 'No unhandled browser or console errors').toEqual([]) })

