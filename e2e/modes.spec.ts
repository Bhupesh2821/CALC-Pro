  const px = pinchRect!.x + pinchRect!.width / 2, py = pinchRect!.y + pinchRect!.height / 2
  await client.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: px - 30, y: py, id: 1 }, { x: px + 30, y: py, id: 2 }] })
