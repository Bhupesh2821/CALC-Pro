test('programmer, converter and engineering copy controls write the actual clipboard', async ({ page, browserName }) => {
  test.skip(browserName !== 'chromium', 'Native clipboard permissions are verified in Chromium; browser permission interfaces differ.')
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write'])
  await page.bringToFront()
  const clipboard = () => page.evaluate(() => navigator.clipboard.readText())
  await mode(page, 'Programmer')
  await page.getByLabel('Programmer input', { exact: true }).fill('255')
  await page.getByRole('button', { name: 'Equals', exact: true }).click()
  for (const [base, expected] of [['DEC', '255'], ['HEX', 'FF'], ['OCT', '377'], ['BIN', '11111111']]) {
    await page.getByRole('button', { name: `Copy ${base}`, exact: true }).click()
    await expect.poll(clipboard).toBe(expected)
  }
  await page.getByRole('button', { name: 'Copy programmer result', exact: true }).click()
  await expect.poll(clipboard).toBe('DEC 255 · HEX FF')
  await mode(page, 'Converter')
  const conversion = await page.getByLabel('Converted value', { exact: true }).textContent()
  await page.getByRole('button', { name: 'Copy conversion result', exact: true }).click()
  await expect.poll(clipboard).toBe(conversion)
  await mode(page, 'Engineering')
  await page.getByRole('button', { name: 'Calculate complex', exact: true }).click()
  await page.getByRole('button', { name: 'Copy engineering result', exact: true }).click()
  await expect.poll(clipboard).toBe('5 − i')
  await page.getByRole('button', { name: 'Matrices', exact: true }).click()
  await page.getByRole('button', { name: 'A + B', exact: true }).click()
  await page.getByRole('button', { name: 'Copy engineering result', exact: true }).click()
  await expect.poll(clipboard).toBe('6\t8\n10\t12')
})
