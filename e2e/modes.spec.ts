  await client.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: px - 60, y: py, id: 1 }, { x: px + 60, y: py, id: 2 }] })
  await client.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] })
